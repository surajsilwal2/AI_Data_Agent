from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        ..., description='List of messages exchanged with the agent')
    user_question: str = Field(..., description='User question for the agent')

    curated_ques: str = Field(...,
                              description='Curated user question for the agent')

    prompt_query_Context: str = Field(
        ..., description='A detailed prompt query with SQL Db context for the agent')

    is_safe: Literal['safe', 'unsafe'] = Field(
        ..., description='Indicates whether the agent is safe or unsafe')
 

    generated_sql_query: str = Field(
        ..., description='The SQL query generated by the agent based on the prompt query context')

    comments: str = Field(..., description='This comments is regarding for the safety of the generated sql query')

    sql_query_execution_result: str = Field(
        ..., description='The result of executing the generated SQL query')

    final_answer: str = Field(
        ..., description='The final answer provided by the agent after processing the SQL query')


class JudgeSchema(BaseModel):
    answer: Literal['yes', 'no'] = Field(..., description='Indicates wether the generated sql query is safe to execute or not')
    comments: str = Field(..., description= 'Additional comments or feedback from the judge regarding the sql query')